"""Generate include/eu4_gog_table.inc from data/rva_map.json.

Usage: python make_table.py STEAM_EXE GOG_EXE

Every mapped address becomes {steam_rva, gog_rva, length, bytes}. For code, `bytes` is the
GOG code at gog_rva and `length` is how far the two builds stay equivalent from there:
instructions with the same mnemonic and operands once branch targets and RIP-relative
displacements are removed, at most 64 bytes. A plugin that checks more bytes than `length`
refuses to patch. Data addresses have length 0.
"""
import json
import os
import re
import sys

import capstone

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from match_functions import BRANCH, RIP, Image  # noqa: E402

ROOT = os.path.dirname(HERE)
WINDOW = 64


def norm(mn, ops):
    ops = RIP.sub('rip+X', ops)
    if BRANCH.match(mn) and ops.startswith('0x'):
        ops = 'T'
    return mn + ' ' + ops


HEXNUM = re.compile(r'0x[0-9a-f]+')


def same_operands(x, y, known):
    """Operands differ only by image-relative constants (e.g. [r13+rax*4+table]) that map."""
    if x[2] != y[2]:
        return False
    sx, sy = norm(x[2], x[3]), norm(y[2], y[3])
    if sx == sy:
        return True
    nx, ny = HEXNUM.findall(sx), HEXNUM.findall(sy)
    if len(nx) != len(ny) or HEXNUM.sub('N', sx) != HEXNUM.sub('N', sy):
        return False
    for p, q in zip(nx, ny):
        if p != q and known.get(int(p, 16)) != int(q, 16):
            return False
    return True


def equivalent_length(a, b, ra, rb, md, known):
    ia = list(md.disasm_lite(a.img[ra:ra + WINDOW + 16], ra))
    ib = list(md.disasm_lite(b.img[rb:rb + WINDOW + 16], rb))
    n = 0
    for x, y in zip(ia, ib):
        if x[1] != y[1] or not same_operands(x, y, known):
            break
        if n + x[1] > WINDOW:
            break
        n += x[1]
    return n


def main():
    a, b = Image(sys.argv[1]), Image(sys.argv[2])
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    m = json.load(open(os.path.join(ROOT, 'data', 'rva_map.json')))
    known = {int(k, 16): int(v['gog'], 16) for k, v in m.items() if v['gog']}
    for s_, g_ in json.load(open(os.path.join(ROOT, 'data', 'functions.json')))['data']:
        known.setdefault(s_, g_)
    rows = []
    for k, v in m.items():
        if not v['gog']:
            continue
        s, g = int(k, 16), int(v['gog'], 16)
        n = equivalent_length(a, b, s, g, md, known) if v['section'] == '.text' else 0
        rows.append((s, g, n, b.img[g:g + n]))
    rows.sort()
    out = os.path.join(ROOT, 'include', 'eu4_gog_table.inc')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by eu4_port/tools/make_table.py. Do not edit.\n')
        f.write('// Steam eu4.exe 1.37.5 RVA -> GOG eu4.exe 1.37.5 RVA, with GOG code bytes.\n')
        for s, g, n, data in rows:
            f.write('{0x%07x, 0x%07x, %2d, "%s"},\n' % (s, g, n, ''.join('\\x%02x' % c for c in data)))
    short = [hex(s) for s, g, n, _ in rows if n == 0 and m['0x%x' % s]['section'] == '.text']
    print('entries', len(rows), '; code with no equivalent bytes:', short)


if __name__ == '__main__':
    main()
